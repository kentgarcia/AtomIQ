/**
 * The platformer's levels (format and legend: `LevelDef` in platformer-core.ts). Framework-free.
 * Story mode (story-levels.ts) gives each one its world, its unit and its questions.
 *
 * Reachability rules (checked by `npm run test:platformer`): the hero jumps 2.9 tiles high and about
 * 4.8 tiles far on the flat, so ground steps stay at 2 tiles or less and gaps at 4 or fewer, unless
 * a spring (about 6 tiles up), a plank, a moving platform or a lift is there to cross it.
 *
 * The first five levels are the tutorial, each introducing something new: 1 walking, jumping, coins,
 * battles and checkpoints; 2 blocks, planks, bricks and spikes; 3 springs and flying foes; 4 moving
 * platforms, lifts, keys and locks; 5 all of it, and the Reactor Slime. Then each unit of the lessons
 * has five levels of its own, one lesson each (Unit 1: 6 gems and bridges, 7 conveyor belts, 8 saws,
 * 9 lava, 10 all of it, and the Reactor Slime again; Unit 2: 11 bridges of logs, 12 gem blocks, 13 islands that halve,
 * 14 steps up and down, 15 all of it and the Reactor Slime).
 */

