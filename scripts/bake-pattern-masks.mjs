/**
 * Bakes the avatar pattern tiles into transparent masks, and writes the source map that lists them.
 *
 * The tiles in assets/images/pattern are opaque: white shapes on a black background. Drawn over a paint
 * they would paint the whole tile, background included. This turns each tile into a mask instead: the
 * shapes become solid and the background fully transparent (the tile's brightness becomes its alpha), so
 * the app can tint the shapes (white, today) and leave the paint around them alone. The originals are
 * not touched.
 *
 * Run after adding or changing a tile:  node scripts/bake-pattern-masks.mjs   (needs ImageMagick 7)
 * Output: assets/images/pattern-mask/pattern_NNN.png and components/avatar/avatar-patterns.ts.
 * Keep `PATTERN_COUNT` in components/avatar/avatar-core.ts equal to the number of tiles (test:avatar checks).
 */
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const FROM = path.join(REPO, "assets/images/pattern");
const TO = path.join(REPO, "assets/images/pattern-mask");

const files = fs.readdirSync(FROM).filter((f) => /^pattern_\d{3}\.png$/.test(f)).sort();
if (files.length === 0) throw new Error(`no tiles in ${FROM}`);
fs.mkdirSync(TO, { recursive: true });

for (const f of files) {
  // Brightness -> alpha over a black canvas: white shape = opaque black, black background = transparent.
  execFileSync("magick", [path.join(FROM, f), "-colorspace", "Gray", "-write", "mpr:g", "+delete", "(", "-size", "256x256", "xc:black", ")", "mpr:g", "-compose", "CopyAlpha", "-composite", `PNG32:${path.join(TO, f)}`]);
}

const lines = [
  "/**",
  " * The pattern masks (assets/images/pattern-mask), by id. React Native only: Metro needs each `require` written",
  " * out. GENERATED by scripts/bake-pattern-masks.mjs: do not edit. The ids (`PATTERN_IDS`) live in `avatar-core.ts`,",
  " * which Node tests can read; `test:avatar` checks the two agree with the folders.",
  " */",
  "",
  'import type { ImageSourcePropType } from "react-native";',
  "",
  'import type { PatternId } from "./avatar-core";',
  "",
  'export const PATTERN_SOURCES: Record<Exclude<PatternId, "none">, ImageSourcePropType> = {',
  ...files.map((f) => `  p${f.slice(8, 11)}: require("@/assets/images/pattern-mask/${f}"),`),
  "};",
  "",
];
fs.writeFileSync(path.join(REPO, "components/avatar/avatar-patterns.ts"), lines.join("\n"));
console.log(`baked ${files.length} masks into assets/images/pattern-mask and rewrote components/avatar/avatar-patterns.ts`);
